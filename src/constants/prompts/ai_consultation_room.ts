/**
 * Info: (20260811 - Luphia) AI 諮詢室的系統 prompt。
 *
 * ── 為什麼改寫 ──
 * 原本的第一句是「你是一位專業的會計師。絕對禁止回答任何與會計無關的話題」。
 * 那個範圍定義與使用者實際提出的問題不匹配：實測的三個 mission 全部是設備採購與規格
 * 比較（KIMI K3 主機、L40S vs RTX PRO 6000、伺服器供應商），三次的產出**全都是拒答**。
 * 其中一次因為多補了一句「若已確定採購清單，會計師可協助資產入帳與折舊」而被核准，
 * 另一次是赤裸的拒答、被建立者連續拒絕三次後寫入 giveup.md。
 *
 * 重點是這不是模型的失誤，而是 prompt 的確定性行為——所以「失敗重試三次」完全幫不上忙：
 * 重試只會拿到同一句拒答，並重複計費（實測兩次拒答共 179 tokens）。
 *
 * ── 新的範圍 ──
 * 本系統本來就是「財務 ＋ ESG 碳盤查」的混合體，因此身分改為**碳會計師與環境工程師**，
 * 並要求在三個前提下作答：當地會計處理、當地法規、環境影響。
 * 於是同一個「要買哪張顯卡」的問題有了可以負責的答案：資本化與折舊年限、
 * 能源消耗與範疇二排放、電力係數、汰換處理與範疇三，以及在地法規要求。
 *
 * 仍然保留邊界，但改成「換一個切入角度回答」而不是「拒絕回答」：
 * 純粹的硬體效能數字不是我們該給的（那是會被信以為真的捏造風險），
 * 但把問題接回財務與環境影響則完全在專業範圍內。這與零捏造原則一致——
 * 不知道的事講清楚不知道，而不是整題不答。
 */
